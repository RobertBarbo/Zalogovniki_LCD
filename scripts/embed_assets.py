"""Generate flash-resident web assets and the approved v5 LCD background."""
from pathlib import Path
import gzip
import hashlib

ROOT = Path(__file__).resolve().parents[1]


def generate():
    assets = {
        'WEB_INDEX_GZIP': gzip.compress((ROOT / 'web/index.html').read_bytes(), mtime=0),
        'WEB_SCRIPT_GZIP': gzip.compress((ROOT / 'web/app.js').read_bytes(), mtime=0),
        'WEB_SENSORS_GZIP': gzip.compress((ROOT / 'web/sensors.html').read_bytes(), mtime=0),
        'WEB_SENSORS_SCRIPT_GZIP': gzip.compress((ROOT / 'web/sensors.js').read_bytes(), mtime=0),
        'LCD_BACKGROUND': (ROOT / 'data/zalogovnik_reference_v5.jpg').read_bytes(),
    }
    header = '#pragma once\n#include <Arduino.h>\n'
    source = '// Generated by scripts/embed_assets.py; do not edit.\n#include "generated_assets.h"\n'
    for name, data in assets.items():
        header += f'extern const uint8_t {name}[] PROGMEM;\nextern const size_t {name}_SIZE;\n'
        source += f'const uint8_t {name}[] PROGMEM = {{\n'
        source += '\n'.join('  ' + ','.join(f'0x{b:02x}' for b in data[i:i+20]) + ','
                            for i in range(0, len(data), 20))
        source += f'\n}};\nconst size_t {name}_SIZE = sizeof({name});\n'
        print(f'{name}: {len(data)} bytes, sha256={hashlib.sha256(data).hexdigest()[:16]}')
    for path, content in [(ROOT / 'include/generated_assets.h', header),
                          (ROOT / 'src/generated_assets.cpp', source)]:
        if not path.exists() or path.read_text(encoding='utf-8') != content:
            path.write_text(content, encoding='utf-8', newline='\n')


if __name__ == '__main__':
    generate()
